#!/usr/bin/env node
/**
 * Copy zxing_reader.wasm from the zxing-wasm version resolved by
 * react-zxing → barcode-detector into public/wasm/.
 *
 * Also writes src/lib/zxing-wasm-asset.ts so the runtime can call
 * prepareWasm() with a cache-busted URL matching that exact binary.
 *
 * Fails hard if the dependency chain or WASM file is missing — never
 * silently keep a stale public binary.
 */
import { createRequire } from "node:module";
import {
  copyFileSync,
  existsSync,
  mkdirSync,
  readFileSync,
  realpathSync,
  statSync,
  writeFileSync
} from "node:fs";
import { createHash } from "node:crypto";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const fieldRoot = join(dirname(fileURLToPath(import.meta.url)), "..");
const requireFromField = createRequire(join(fieldRoot, "package.json"));

function packageRootFromEntry(entryPath, expectedName) {
  let dir = dirname(entryPath);
  while (dir !== "/") {
    const pkgPath = join(dir, "package.json");
    if (existsSync(pkgPath)) {
      const pkg = JSON.parse(readFileSync(pkgPath, "utf8"));
      if (!expectedName || pkg.name === expectedName) {
        return { root: dir, pkg };
      }
    }
    dir = dirname(dir);
  }
  throw new Error(
    `Could not find package${expectedName ? ` ${expectedName}` : ""} above ${entryPath}`
  );
}

function sha256File(filePath) {
  return createHash("sha256").update(readFileSync(filePath)).digest("hex");
}

const reactZxingEntry = requireFromField.resolve("react-zxing", { paths: [fieldRoot] });
const { root: reactZxingRoot, pkg: reactZxingPkg } = packageRootFromEntry(
  reactZxingEntry,
  "react-zxing"
);

const barcodeDetectorLink = join(dirname(reactZxingRoot), "barcode-detector");
if (!existsSync(barcodeDetectorLink)) {
  throw new Error(
    `barcode-detector not found next to react-zxing at ${barcodeDetectorLink}`
  );
}
const barcodeDetectorRoot = realpathSync(barcodeDetectorLink);
const barcodeDetectorPkg = JSON.parse(
  readFileSync(join(barcodeDetectorRoot, "package.json"), "utf8")
);
const requireFromBarcodeDetector = createRequire(
  join(barcodeDetectorRoot, "package.json")
);

let sourceWasm;
try {
  sourceWasm = requireFromBarcodeDetector.resolve(
    "zxing-wasm/reader/zxing_reader.wasm"
  );
} catch (error) {
  let zxingWasmEntry;
  try {
    zxingWasmEntry = requireFromBarcodeDetector.resolve("zxing-wasm");
  } catch (resolveError) {
    throw new Error(
      `zxing-wasm not resolvable from barcode-detector@${barcodeDetectorPkg.version}: ${
        resolveError instanceof Error ? resolveError.message : String(resolveError)
      }`
    );
  }
  const { root: zxingWasmRoot } = packageRootFromEntry(zxingWasmEntry, "zxing-wasm");
  sourceWasm = join(zxingWasmRoot, "dist/reader/zxing_reader.wasm");
}

const { root: zxingWasmRoot, pkg: zxingWasmPkg } = packageRootFromEntry(
  sourceWasm,
  "zxing-wasm"
);

if (!existsSync(sourceWasm)) {
  throw new Error(`WASM binary missing at ${sourceWasm}`);
}

const destDir = join(fieldRoot, "public/wasm");
const destWasm = join(destDir, "zxing_reader.wasm");
mkdirSync(destDir, { recursive: true });
copyFileSync(sourceWasm, destWasm);

const srcStat = statSync(sourceWasm);
const destStat = statSync(destWasm);
const srcHash = sha256File(sourceWasm);
const destHash = sha256File(destWasm);

if (srcStat.size !== destStat.size || srcHash !== destHash) {
  throw new Error(
    `WASM sync failed: size/hash mismatch (src ${srcStat.size}/${srcHash} vs dest ${destStat.size}/${destHash})`
  );
}

const shortHash = destHash.slice(0, 12);
const publicPath = `/wasm/zxing_reader.wasm?v=${shortHash}`;
const assetModule = `/* AUTO-GENERATED by scripts/sync-zxing-wasm.mjs — do not edit. */
export const ZXING_WASM_PACKAGE_VERSION = ${JSON.stringify(zxingWasmPkg.version)} as const;
export const ZXING_WASM_SHA256 = ${JSON.stringify(destHash)} as const;
export const ZXING_WASM_BYTES = ${destStat.size} as const;
export const ZXING_WASM_PUBLIC_PATH = "/wasm/zxing_reader.wasm" as const;
export const ZXING_WASM_URL = ${JSON.stringify(publicPath)} as const;
export const REACT_ZXING_VERSION = ${JSON.stringify(reactZxingPkg.version)} as const;
export const BARCODE_DETECTOR_VERSION = ${JSON.stringify(barcodeDetectorPkg.version)} as const;
`;

writeFileSync(join(fieldRoot, "src/lib/zxing-wasm-asset.ts"), assetModule);

console.log(
  `[sync-zxing-wasm] react-zxing@${reactZxingPkg.version} → barcode-detector@${barcodeDetectorPkg.version} → zxing-wasm@${zxingWasmPkg.version}\n` +
    `  source: ${zxingWasmRoot}\n` +
    `  → public/wasm/zxing_reader.wasm (${destStat.size} bytes, sha256=${shortHash}…)\n` +
    `  → src/lib/zxing-wasm-asset.ts (url ${publicPath})`
);
